function mdl = train_SVMReg_BayesianOptim(X,Y,Niter,K)
% mdl - Bayesian trained model

lmbd = optimizableVariable('Lambda', [1,1e3]/length(Y));
sct = optimizableVariable('ScoreTransform', {'none','doublelogit','invlogit','logit'}, 'Type', 'categorical');
c = cvpartition(length(Y), 'Kfold', K);
fun = @(x)kfoldLoss(fitclinear(X,Y,'ObservationsIn','rows','CVPartition',c,...
    'Learner','svm','Solver','sparsa','Regularization','lasso',...
    'Lambda',x.Lambda,'ScoreTransform',char(x.ScoreTransform),'GradientTolerance',1e-8));
results = bayesopt(fun, [lmbd sct], 'MaxObjectiveEvaluations', Niter, ...
    'AcquisitionFunctionName', 'expected-improvement-plus', 'Verbose', 0, 'PlotFcn', []);
mdl = fitclinear(X,Y,'ObservationsIn','rows','Learner','svm','Solver','sparsa',...
    'Regularization','lasso','Lambda',results.XAtMinObjective.Lambda,...
    'ScoreTransform',char(results.XAtMinObjective.ScoreTransform),'GradientTolerance',1e-8);